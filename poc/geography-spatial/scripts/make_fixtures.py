#!/usr/bin/env python
"""Generate SYNTHETIC boundary fixtures for the OpenAid geography PoC.

The output files are deterministic, labelled synthetic test data — they are
NOT real-world boundaries and must never be presented as real evidence.

Three countries with deliberately different hierarchy shapes (ISO 3166
user-assigned codes XA–XZ so they can never collide with real countries):

* XA Alandra  — 2 levels (Region → District)
* XB Boroland — 3 levels (Province → County → Ward)
* XC Cyria    — 4 levels (Governorate → Department → Commune → Village)

Geometries are simple rectangular tilings in EPSG:4326 with shared edges:
valid, non-overlapping, and easy to assert on in tests.

Run from poc/geography-spatial:  python scripts/make_fixtures.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIXTURES = HERE.parent / "fixtures"


def rect(x0: float, y0: float, x1: float, y1: float) -> dict:
    return {
        "type": "Polygon",
        "coordinates": [[[x0, y0], [x1, y0], [x1, y1], [x0, y1], [x0, y0]]],
    }


def feature(code: str, name: str, level: int, parent: str | None, geom: dict, iso3: str) -> dict:
    return {
        "type": "Feature",
        "geometry": geom,
        "properties": {
            "country_iso3": iso3,
            "official_code": code,
            "source_unit_id": code,
            "name": name,
            "admin_level": level,
            "parent_code": parent,
        },
    }


def collection(features: list[dict]) -> dict:
    return {"type": "FeatureCollection", "features": features}


def write_country(dirname: str, country: dict, features: list[dict]) -> None:
    out = FIXTURES / dirname
    out.mkdir(parents=True, exist_ok=True)
    (out / "boundary.geojson").write_text(
        json.dumps(collection(features), indent=1), encoding="utf-8"
    )
    (out / "country.yaml").write_text(country, encoding="utf-8")
    print(f"wrote {out} ({len(features)} features)")


# ---------------------------------------------------------------------------
# XA — Alandra: 2 levels (Region 1 → District 2)
# 3 regions in a row; each region split into 2 districts stacked on latitude.
# ---------------------------------------------------------------------------


def make_xa() -> None:
    feats = []
    for i in (1, 2, 3):
        x0, x1 = (i - 1) * 2.0, i * 2.0
        feats.append(feature(f"XA-R{i}", f"Region {i}", 1, None, rect(x0, 0, x1, 2), iso3="XAA"))
        for j in (1, 2):
            feats.append(
                feature(
                    f"XA-D{i}{j}",
                    f"District {i}{j}",
                    2,
                    f"XA-R{i}",
                    rect(x0, j - 1.0, x1, float(j)),
                    iso3="XAA",
                )
            )
    country = """\
# =========================================================================
# SYNTHETIC TEST FIXTURE — the Republic of Alandra does not exist.
# Generated by scripts/make_fixtures.py for the OpenAid geography PoC.
# Never present this data as real-world evidence.
# =========================================================================
iso2: XA
iso3: XAA
name: Alandra
official_name: Republic of Alandra (synthetic)
capital: Port Alandra
region: Southern Africa (synthetic)
status: placeholder
languages:
  - English (synthetic)
currency: ALD
timezone: UTC+02:00 (synthetic)
levels:
  - level_number: 1
    level_name: Region
    description: Synthetic top-level division of Alandra
  - level_number: 2
    level_name: District
    description: Synthetic second-level division of Alandra
"""
    write_country("XA_alandra", country, feats)


# ---------------------------------------------------------------------------
